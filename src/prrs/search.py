def _refuse_unaffordable_enumeration(atoms, config):
    """Refuse to start an exhaustive run the trial budget cannot pay for.

    The point of `direction_mode = "exhaustive"` is that a negative result becomes
    admissible, and it stops being admissible the moment the enumeration is truncated --
    a truncated exhaustive run is a sampled run wearing the wrong label. So this fails
    BEFORE any potential evaluation rather than an hour in: proposing is pure geometry,
    so the count is free, while discovering the shortfall at trial 96 costs a GPU day and
    leaves a record whose own mode field is a lie.

    It counts the source structure only. A deeper microstate can offer more candidates,
    and the loop's own ledger catches that case (a truncated exhaustive proposal leaves
    directions in `not_executed_ids`), but the common failure -- a budget set for sampled
    mode and a mode flipped afterwards -- is caught here, cheaply and early.
    """
    report = {}
    batches = list(propose(atoms, config, config.seed, report=report))
    needed = sum(len(batch) for batch in batches)
    # ALL the budgets that can cut one microstate's enumeration, not just max_trials.
    # b05's probe2 is why this line names three: `may_search` stops a microstate at
    # `conformer_trials_per_microstate` (32 by default) and a node at
    # `chemical_trials_per_node`, so an exhaustive run needing 504 trials would have been
    # waved through by a raised max_trials and then truncated at 32 anyway -- the ledger
    # would have caught it afterwards, which is exactly what "before starting" rules out.
    budgets = {
        "max_trials": config.max_trials,
        "chemical_trials_per_node": config.chemical_trials_per_node,
        "conformer_trials_per_microstate": config.conformer_trials_per_microstate,
    }
    binding = {name: value for name, value in budgets.items() if needed > value}
    if binding:
        raise ValueError(
            f"direction_mode='exhaustive' needs {needed} trials for the source structure "
            f"({report.get('selected_total')} directions x their amplitudes) and these "
            f"budgets are smaller: {binding}. Raise every one of them to at least "
            f"{needed}, or run in 'sampled' mode and accept that every negative result "
            f"carries the sampling limit. Refused before starting: a truncated exhaustive "
            f"run is a sampled run with the wrong label on it."
        )
    return needed


class DirectionSchedule:
    """Who was proposed, who ran, and why the rest did not.

    Extracted from ReactionSearch.run because the 2026-09-09 ruling makes this the thing
    the record is judged on: a null result is only a result if the ledger can say the
    direction was searched, rather than never selected, never executed, or refused at a
    gate. Only this slice moved -- the loop it serves is unchanged -- because run()
    captures several mutable registries and a wholesale rewrite has no net under it
    (REVIEW_2026-09-05.md 5.2).

    Two units, kept apart on purpose:

        directions   one proposed coordinate. `propose` yields one batch per direction.
        amplitudes   the samples inside one direction's batch.

    Adding them together is meaningless and an early draft of the test for this class
    did it. `directions_*` answers "was this coordinate tried at all", which is what a
    channel-level verdict needs; `amplitudes_*` answers "how far along it did we get",
    which is what a bracket needs.

    Nothing here decides anything. It observes the loop and writes down what happened,
    so the scheduling policy stays where it is until it is deliberately changed.
    """

    def __init__(self, report):
        self.report = report or {}
        self.selected = list(self.report.get("selected_ids") or [])
        self.offered = {}  # direction id -> amplitudes offered
        self.executed = {}  # direction id -> amplitudes executed
        self.halted = {}  # direction id -> why it stopped short
        self.order = []  # direction ids in the order the loop saw them

    def offer(self, probes):
        """One direction's batch arrives. Returns its id."""
        probe = probes[0]
        key = candidate_id(probe.family, probe.indices, probe.sign)
        if key not in self.offered:
            self.order.append(key)
        self.offered[key] = self.offered.get(key, 0) + len(probes)
        self.executed.setdefault(key, 0)
        return key

    def ran(self, key):
        self.executed[key] = self.executed.get(key, 0) + 1

    def stopped(self, key, reason):
        """This direction stopped before its batch was finished."""
        self.halted.setdefault(key, reason)

    def never_offered(self, reason):
        """The proposal had more directions but the loop stopped asking for them.

        `propose` is a generator: the ids it selected are known up front from its report,
        while the batches arrive lazily. So the directions that were selected and never
        even reached the loop are exactly selected minus offered, and the reason belongs
        to whatever broke the loop.
        """
        for key in self.selected:
            if key not in self.offered:
                self.halted.setdefault(key, reason)

    def schedule_of(self, key):
        """The per-scan record: one direction, in amplitude units."""
        offered = self.offered.get(key, 0)
        executed = self.executed.get(key, 0)
        return {
            "direction_id": key,
            "amplitudes_offered": offered,
            "amplitudes_executed": executed,
            "amplitudes_not_executed": offered - executed,
            "halted_by": self.halted.get(key),
            "meaning": (
                "amplitudes of THIS direction; amplitudes_not_executed is not a "
                "negative result about them, it is the absence of one"
            ),
        }

    def ledger(self):
        """The run-level record, in direction units."""
        executed_ids = [k for k, n in self.executed.items() if n > 0]
        not_executed = [k for k in self.selected if k not in executed_ids]
        reasons = Counter(self.halted.get(k) or "unknown" for k in not_executed)
        return {
            "directions_selected": len(self.selected),
            "directions_executed": len(executed_ids),
            "directions_not_executed": len(not_executed),
            "executed_ids": sorted(executed_ids),
            "not_executed_ids": sorted(not_executed),
            "not_executed_reasons": dict(reasons),
            "coverage_censored": bool(self.report.get("coverage_censored") or not_executed),
            "censored_by": self.report.get("censored_by"),
            "uncovered_ids": list(self.report.get("uncovered_ids") or []),
            "meaning": (
                "candidate -> selected -> executed, with a reason for every selected "
                "direction that did not run. A direction in not_executed_ids was NOT "
                "searched, so no negative conclusion about it is admissible; "
                "uncovered_ids were never even selected (see censored_by)"
            ),
        }


def _bracket_high(record):
    """The bracket fields that describe its high end, derived from one record.

    Refinement replaces the high end, so these have to be recomputed from whichever
    record ends up there rather than kept from the coarse sample. They were not: a coarse
    high that stopped on a ridge left `high_kind = "boundary_unattributed"` and
    `target_microstate = None` standing even after refinement reached a confirmed
    product, and a refinement that departed to a different microstate than the coarse
    high left the coarse one's id in place. Both report a window that was measured on a
    different amplitude than the one named.
    """
    return {
        "target_microstate": record.get("target_microstate"),
        "high_kind": {
            "completed": "confirmed",
            "ts_candidate": "boundary_unattributed",
        }.get(record["status"], "transient_crossing"),
    }


def _rebuild_for_resume(output, cfg):
    """Reconstruct a dead run's state from disk (PLAN items 6.2-6.5).

    A process kill leaves network.json at status "running" with the last published
    scan as the consistent boundary. Everything after that boundary is in flight and
    is ROLLED BACK: attempt rows not referenced by any published scan are dropped from
    attempts.jsonl and their trial directories deleted, because re-running the
    direction from the queue would otherwise duplicate them. Deletion is the one place
    this touches already-written data, so it is named in resume.json -- a separate
    file, deliberately NOT inside network.json, or the acceptance criterion (resumed
    run byte-identical to an uninterrupted one) could not even be stated.

    Refuses (never guesses) when: the network is not mid-run, the config differs, the
    implementation fingerprint differs (a resume across implementations is a mixed
    batch -- this project retired one of those already), or a queued pair is missing
    from the rebuilt registry.
    """
    network_path = output / "network.json"
    if not network_path.exists():
        raise FileNotFoundError(f"resume needs {network_path}")
    network = json.loads(network_path.read_text(encoding="utf-8-sig"))
    if network.get("status") != "running":
        raise ValueError(
            f"resume needs a mid-run network (status 'running'); this one is "
            f"{network.get('status')!r}"
        )
    manifest = json.loads((output / "config.json").read_text(encoding="utf-8-sig"))
    # JSON round-trips tuples as lists, so compare through the same serialisation
    # rather than letting the container types veto an identical config
    if json.loads(json.dumps(cfg.to_dict())) != manifest.get("config"):
        raise ValueError("resume refused: config.json differs from the supplied config")
    source_hash = hashlib.sha256()
    for path in sorted(Path(__file__).parent.glob("*.py")):
        source_hash.update(path.name.encode())
        source_hash.update(path.read_bytes())
    if manifest.get("implementation_sha256") != source_hash.hexdigest():
        raise ValueError(
            "resume refused: implementation_sha256 differs from the tree -- a resume "
            "across implementations is a mixed batch"
        )

    keep = set()
    for scan in network.get("amplitude_scans") or []:
        keep.update(sample["attempt"] for sample in scan.get("samples") or [])
    keep.update(candidate["attempt"] for candidate in network.get("ts_candidates") or [])
    keep.update(
        withheld["attempt"]
        for withheld in network.get("withheld_candidates") or []
        if withheld.get("attempt")
    )
    for edge in network.get("reactions") or []:
        keep.update(edge.get("attempts") or [])
        keep.update(c.get("seed_attempt") for c in edge.get("continuations") or [])

    records, lines, dropped_rows = [], [], 0
    jsonl = output / "attempts.jsonl"
    if jsonl.exists():
        for line in jsonl.read_text(encoding="utf-8").splitlines():
            if not line.strip():
                continue
            record = json.loads(line)
            if record.get("attempt_id") in keep:
                records.append(record)
                lines.append(line)
            else:
                dropped_rows += 1
    if dropped_rows:
        jsonl.write_text("\n".join(lines) + ("\n" if lines else ""), encoding="utf-8")

    published_scans = len(network.get("amplitude_scans") or [])
    deleted = []
    trials_dir = output / "trials"
    if trials_dir.exists():
        for entry in sorted(trials_dir.iterdir()):
            name = entry.name
            if len(name) == 7 and name.startswith("t") and name[1:].isdigit():
                if name not in keep:
                    shutil.rmtree(entry)
                    deleted.append(name)
            elif name.startswith("c") and "s" in name:
                # committor shots: c###b##s#### -- the leading number is the scan
                # index, so anything at or past the published boundary is in flight
                try:
                    scan_index = int(name[1:].split("b", 1)[0])
                except ValueError:
                    continue
                if scan_index >= published_scans:
                    shutil.rmtree(entry)
                    deleted.append(name)

    registry = Registry.from_network(network, output, cfg)
    paths_dir = output / "paths"
    saddle_searches = len(list(paths_dir.glob("climb*"))) if paths_dir.exists() else 0
    continuations = len(list(paths_dir.glob("continuation*"))) if paths_dir.exists() else 0
    node_by_id = {node.id: node for node in registry.nodes}
    pair_by_state = {
        state.id: (node, state) for node in registry.nodes for state in node.microstates
    }
    queue = deque()
    for node_id, state_id in network.get("queue") or []:
        node = node_by_id.get(node_id)
        pair = pair_by_state.get(state_id)
        if node is None or pair is None or pair[0] is not node:
            raise ValueError(
                f"resume refused: queued pair {node_id}/{state_id} is not in the "
                "rebuilt registry"
            )
        queue.append((node, pair[1]))

    schedules = {}
    for scan in network.get("amplitude_scans") or []:
        state_id = scan["source_microstate"]
        proposal = scan.get("proposal") or {}
        schedule = schedules.setdefault(
            state_id, DirectionSchedule(proposal.get("budget") or {})
        )
        per = proposal.get("schedule") or {}
        key = per.get("direction_id")
        if key is None:
            continue
        if key not in schedule.offered:
            schedule.order.append(key)
        schedule.offered[key] = max(
            schedule.offered.get(key, 0), per.get("amplitudes_offered", 0)
        )
        schedule.executed[key] = max(
            schedule.executed.get(key, 0), per.get("amplitudes_executed", 0)
        )
        if per.get("halted_by"):
            schedule.halted.setdefault(key, per["halted_by"])

    # Admissions at the depth cap, derived: every admission to a node at (or past)
    # max_depth happened at that fixed depth, and only new admissions reach the cap
    # branch -- so the count is the node's microstates plus its evictions.
    depth_capped = [
        state.id
        for node in registry.nodes
        if node.depth >= cfg.max_depth
        for state in node.microstates
    ] + [
        entry["id"]
        for node in registry.nodes
        if node.depth >= cfg.max_depth
        for entry in node.evicted
    ]

    atomic_json(
        output / "resume.json",
        {
            "dropped_attempt_rows": dropped_rows,
            "deleted_trial_dirs": deleted,
            "rebuilt_records": len(records),
            "queue_length": len(queue),
            "meaning": (
                "rollback to the last published scan boundary; every deletion is "
                "named here because it is the only place resume touches written data"
            ),
        },
    )
    return {
        "manifest": manifest,
        "network": network,
        "registry": registry,
        "records": records,
        "ts_candidates": network.get("ts_candidates") or [],
        "saddle_searches": saddle_searches,
        "continuations": continuations,
        "queue": queue,
        "schedules": schedules,
        "depth_capped": depth_capped,
    }


